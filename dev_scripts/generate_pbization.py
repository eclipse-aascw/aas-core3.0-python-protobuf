"""Run the pbization generation."""

import argparse
import os
import pathlib
import re
import sys

import aas_core_meta.v3
import aas_core_codegen.main

# NOTE (aaronzi, 2026-11-05):
# aas-core-codegen does not emit any copyright or license information, so we
# prepend the header to the generated module ourselves. Otherwise, the header
# would be lost on every re-generation.
#
# REUSE-IgnoreStart
_LICENSE_HEADER = """\
# SPDX-FileCopyrightText: 2023 aas-core3.0-python-protobuf AUTHORS
#
# SPDX-License-Identifier: MIT

"""
# REUSE-IgnoreEnd

_LEADING_SPDX_COMMENTS_RE = re.compile(r"\A(?:#\s*(?:SPDX-[A-Za-z-]+:.*)?\n|\n)*")

_GENERATED_MARKER = "# Automatically generated with python_protobuf/main.py."


def _prepend_license_header(text: str) -> str:
    """Replace any leading SPDX comment block in ``text`` with our license header."""
    return _LICENSE_HEADER + _LEADING_SPDX_COMMENTS_RE.sub("", text, count=1)


def _add_license_headers(output_dir: pathlib.Path) -> None:
    """Prepend the license header to all the modules generated by aas-core-codegen."""
    for path in sorted(output_dir.glob("*.py")):
        text = path.read_text(encoding="utf-8")
        if _GENERATED_MARKER not in text:
            continue

        path.write_text(_prepend_license_header(text), encoding="utf-8")


def main() -> int:
    """Execute the main routine."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.parse_args()

    assert aas_core_meta.v3.__file__ is not None

    this_path = pathlib.Path(os.path.realpath(__file__))

    output_dir = this_path.parent.parent / "aas_core3_protobuf"

    exit_code = aas_core_codegen.main.execute(
        aas_core_codegen.main.Parameters(
            model_path=pathlib.Path(aas_core_meta.v3.__file__),
            target=aas_core_codegen.main.Target.PYTHON_PROTOBUF,
            snippets_dir=this_path.parent / "snippets",
            output_dir=output_dir,
        ),
        stdout=sys.stdout,
        stderr=sys.stderr,
    )
    if exit_code != 0:
        return exit_code

    _add_license_headers(output_dir)

    return 0


if __name__ == "__main__":
    sys.exit(main())
